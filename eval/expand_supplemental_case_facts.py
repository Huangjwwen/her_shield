class TextExtractor(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        if tag in {"script", "style", "noscript"}:
            self.skip += 1
        if tag in {"p", "div", "li", "h1", "h2", "h3", "h4", "br"}:
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in {"script", "style", "noscript"} and self.skip:
            self.skip -= 1
        if tag in {"p", "div", "li", "h1", "h2", "h3", "h4"}:
            self.parts.append("\n")

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(data)


def clean(text):
    text = html.unescape(text or "").replace("\u3000", " ").replace("\xa0", " ")
    return re.sub(r"\s+", " ", text).strip()


def cache_stem(url):
    return re.sub(r"[^a-zA-Z0-9]+", "_", url)[-140:]


def legacy_cache_path(url):
    return LEGACY_CACHE / (re.sub(r"[^a-zA-Z0-9]+", "_", url)[-100:] + ".txt")


def decode_html(raw, charset):
    encodings = [charset, "utf-8", "gb18030"]
    markup = None
    for encoding in filter(None, encodings):
        try:
            markup = raw.decode(encoding)
            break
        except (UnicodeDecodeError, LookupError):
            continue
    if markup is None:
        markup = raw.decode("utf-8", errors="replace")
    parser = TextExtractor()
    parser.feed(markup)
    return "\n".join(clean(line) for line in "".join(parser.parts).splitlines() if clean(line))


def fetch_source(url):
    CACHE.mkdir(exist_ok=True)
    text_path = CACHE / (cache_stem(url) + ".txt")
    if text_path.exists():
        return text_path.read_text(encoding="utf-8"), "cache"
    legacy = legacy_cache_path(url)
    if legacy.exists():
        text = legacy.read_text(encoding="utf-8")
        text_path.write_text(text, encoding="utf-8")
        return text, "legacy_cache"

    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request, timeout=45) as response:
        raw = response.read()
        content_type = response.headers.get_content_type()
        charset = response.headers.get_content_charset()
    if content_type == "application/pdf" or raw.startswith(b"%PDF") or url.lower().endswith(".pdf"):
        reader = PdfReader(io.BytesIO(raw))
        text = "\n".join(page.extract_text() or "" for page in reader.pages)
    else:
        text = decode_html(raw, charset)
    text = text.replace("\x00", "")
    text_path.write_text(text, encoding="utf-8")
    return text, "downloaded"


def title_candidates(title):
    title = title.removesuffix("案")
    candidates = [title, title[:18], title[:14], title[:10]]
    return [candidate for candidate in dict.fromkeys(candidates) if len(candidate) >= 8]


def locate(text, title, ordinal):
    for candidate in title_candidates(title):
        position = text.rfind(candidate)
        if position >= 0:
            return position, f"title:{candidate}"
    fact_markers = list(re.finditer(
        r"(?:【|〖)?(?:基本案情|案情简介|简要案情|案情回顾)(?:】|〗)?[:：]?", text
    ))
    if not fact_markers:
        return -1, "not_found"
    names = set(re.findall(r"[\u4e00-\u9fff]{1,3}某(?:某)?", title))
    keywords = [
        term for term in (
            "性骚扰", "猥亵", "性侵", "亲吻", "搂抱", "摸胸", "臀部", "暧昧", "低俗",
            "怀孕", "孕期", "产假", "哺乳", "生育", "婚育", "招聘", "应聘", "求职",
            "限男性", "男性优先", "调岗", "降薪", "解除", "辞退", "退休", "就业歧视",
        ) if term in title
    ]
    scored = []
    for marker in fact_markers:
        start = marker.start()
        sample = text[max(0, start - 350):start + 2500]
        name_hits = sum(name in sample for name in names)
        keyword_hits = sum(keyword in sample for keyword in keywords)
        title_chars = set(re.sub(r"[某案劳动合同纠纷诉与公司员工职工]", "", title))
        char_hits = sum(char in sample for char in title_chars)
        score = name_hits * 12 + keyword_hits * 6 + min(char_hits, 12)
        scored.append((score, start, name_hits, keyword_hits))
    score, position, name_hits, keyword_hits = max(scored)
    if names and not name_hits:
        return -1, "semantic_name_mismatch"
    if keywords and not keyword_hits:
        return -1, "semantic_topic_mismatch"
    if score < 8:
        return -1, "semantic_low_score"
    return position, f"semantic:{score}"


def validate_fact(title, fact):
    names = set(re.findall(r"[\u4e00-\u9fff]{1,3}某(?:某)?|[\u4e00-\u9fff]{1,2}(?:女士|先生)", title))
    if names and not any(name in fact for name in names):
        return False, "name_mismatch"
    topic_groups = (
        (("性骚扰", "骚扰", "猥亵", "性侵", "摸胸", "亲吻", "搂抱", "低俗", "暧昧"),
         ("性骚扰", "骚扰", "猥亵", "性侵", "摸胸", "亲吻", "搂抱", "低俗", "暧昧", "不当行为")),
        (("怀孕", "孕期", "产假", "哺乳", "婚育"),
         ("怀孕", "孕期", "妊娠", "产假", "生育", "哺乳", "婚育")),
        (("招聘", "应聘", "求职"), ("招聘", "应聘", "求职", "录用", "招用")),
        (("女职工", "劳动保护", "社会保险", "参保"),
         ("女职工", "女性职工", "劳动", "休假", "体检", "社会保险", "参保")),
    )
    for title_terms, fact_terms in topic_groups:
        if any(term in title for term in title_terms) and not any(term in fact for term in fact_terms):
            return False, "topic_mismatch"
    return True, "passed"


def extract_fact(text, title, ordinal):
    position, method = locate(text, title, ordinal)
    if position < 0:
        return "", method
    section = text[position:position + 9000]
    start = re.search(r"(?:基本案情|案情简介|简要案情|案情回顾|事实与理由)[:：]?", section)
    if start:
        section = section[start.end():]
    stop = re.search(
        r"(?:裁判结果|裁判理由及结果|裁判情况|仲裁结果|仲裁请求|申请人请求|原告诉讼请求|案件结果|处理结果|"
        r"一审法院|二审法院|法院观点|法院判决|法院认为|法院审理|本院认为|仲裁委裁决|"
        r"检察机关履职情况|调查和督促履职|典型意义|案例分析|综合点评|专家点评|法官说法|"
        r"救助过程|发现处置|案件主要争议焦点|评析)[:：]?",
        section,
    )
    if stop:
        section = section[:stop.start()]
    sentences = re.split(r"(?<=[。！？；])", clean(section))
    leak_terms = ("裁判要旨", "判决如下", "驳回上诉", "本院认为", "法院认为")
    kept = []
    for sentence in sentences:
        if len(sentence) < 12 or any(term in sentence for term in leak_terms):
            continue
        kept.append(sentence)
        if sum(len(item) for item in kept) >= 800:
            break
    return clean("".join(kept))[:1000], method


