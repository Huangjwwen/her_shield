def sentences(text):
    text = re.split(
        r"【(?:检察机关履职情况|专家点评|典型意义|以案说法|裁判结果|裁判要旨|评析)】|"
        r"(?:检察机关履职情况|专家点评|典型意义|裁判结果|裁判要旨)[:：]",
        text or "",
        maxsplit=1,
    )[0]
    text = re.sub(r"\s+", " ", text).strip()
    return [part.strip() for part in re.split(r"(?<=[。！？；])", text) if part.strip()]


def classify(sentence):
    labels = [name for name, pattern in LABEL_PATTERNS.items() if pattern.search(sentence)]
    return labels


PROCEDURE_CUTOFF = re.compile(
    r"(?:随后|此后|后|因而|因此)?(?:向|诉至)(?:劳动人事争议)?仲裁(?:委员会|委|庭)|"
    r"(?:随后|此后|后|因而|因此)?(?:向|诉至).{0,18}(?:人民法院|法院)(?:起诉|提起诉讼)|"
    r"(?:随后|此后|后)?申请仲裁|(?:原告|申请人)(?:遂|后)?(?:起诉|诉至|申请仲裁)|"
    r"(?:请求|诉请)(?:判令|法院|支持|确认|支付|撤销)|"
    r"(?:劳动人事争议)?仲裁委员会|仲裁委裁决|一审(?:法院)?(?:判决|认为|查明)|"
    r"二审(?:法院)?(?:判决|认为|查明)|本院(?:认为|查明|判决|裁定)"
)
JUDICIAL_SENTENCE = re.compile(
    r"^(?:本院|法院|一审法院|二审法院|审理法院|仲裁委|仲裁庭|生效裁判|再审法院)"
)


def post_clean_fact(text):
    """Remove procedural tails that remain attached to otherwise useful fact sentences."""
    result = []
    for sentence in re.split(r"(?<=[。！？；])", text or ""):
        sentence = sentence.strip()
        if not sentence or JUDICIAL_SENTENCE.search(sentence):
            continue
        cutoff = PROCEDURE_CUTOFF.search(sentence)
        if cutoff:
            sentence = sentence[:cutoff.start()].rstrip("，；。 ")
            if sentence:
                sentence += "。"
        if re.search(r"《[^》]+》第[一二三四五六七八九十百零0-9]+条", sentence):
            continue
        if sentence:
            result.append(sentence)
    return "".join(result).strip()


